#!/usr/bin/env bash
set -Eeuo pipefail

command -v arm-vita-eabi-gcc >/dev/null || {
  echo "ERROR: arm-vita-eabi-gcc is missing from the VitaSDK image." >&2
  exit 1
}
command -v arm-vita-eabi-g++ >/dev/null || {
  echo "ERROR: arm-vita-eabi-g++ is missing from the VitaSDK image." >&2
  exit 1
}
[[ -d RecompiledFuncs ]] || {
  echo "ERROR: RecompiledFuncs was not generated by N64Recomp." >&2
  exit 1
}

mkdir -p /workspace/work/vita-objects
common=(-fno-strict-aliasing -Wno-unused-variable -Wno-implicit-function-declaration)
# Match the generated-code target's include directories in the upstream CMakeLists.txt.
includes=(
  -Iinclude
  -Ilib/N64ModernRuntime/ultramodern/include
  -Ilib/N64ModernRuntime/librecomp/include
  -Ilib/N64ModernRuntime/N64Recomp/include
)
count=0

for src in RecompiledFuncs/*.c; do
  [[ -f "$src" ]] || continue
  out="/workspace/work/vita-objects/$(basename "$src").o"
  echo "Vita C compile: $src"
  arm-vita-eabi-gcc -std=c17 "${common[@]}" "${includes[@]}" -c "$src" -o "$out"
  count=$((count + 1))
done

for src in RecompiledFuncs/*.cpp; do
  [[ -f "$src" ]] || continue
  out="/workspace/work/vita-objects/$(basename "$src").o"
  echo "Vita C++ compile: $src"
  arm-vita-eabi-g++ -std=c++20 "${common[@]}" "${includes[@]}" -c "$src" -o "$out"
  count=$((count + 1))
done

[[ "$count" -gt 0 ]] || {
  echo "ERROR: no generated C/C++ source files were found." >&2
  exit 1
}
# First runtime-port checkpoint: compile ultramodern itself for the Vita.
# This deliberately stops before linking or claiming a working renderer.
runtime_dir="lib/N64ModernRuntime/ultramodern"
runtime_includes=(
  -I"$runtime_dir/include"
  -Ilib/N64ModernRuntime/thirdparty
  -Ilib/N64ModernRuntime/thirdparty/concurrentqueue
  -Ilib/N64ModernRuntime/thirdparty/sse2neon
)
runtime_count=0
mkdir -p /workspace/work/vita-runtime-objects
for src in "$runtime_dir"/src/*.cpp; do
  [[ -f "$src" ]] || continue
  out="/workspace/work/vita-runtime-objects/$(basename "$src").o"
  echo "Vita runtime C++ compile: $src"
  arm-vita-eabi-g++ -std=c++20 -fno-strict-aliasing -Wno-unused-parameter \
    "${runtime_includes[@]}" -c "$src" -o "$out"
  runtime_count=$((runtime_count + 1))
done
[[ "$runtime_count" -gt 0 ]] || {
  echo "ERROR: no ultramodern runtime source files were found." >&2
  exit 1
}
echo "VITA_ULTRAMODERN_COMPILE_OK: compiled $runtime_count runtime source files."
echo "VITA_GAME_CODE_COMPILE_OK: compiled $count generated source files."
